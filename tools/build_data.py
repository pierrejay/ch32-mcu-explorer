#!/usr/bin/env python3
"""Merge data/parts/*.json into js/data.js and validate every record.

Python 3 stdlib only. The site itself needs no build: js/data.js is committed.
Run after editing any file in data/parts/:   python3 tools/build_data.py
Exit code 1 if validation errors are found (data.js is not written).
"""
import datetime
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PARTS = os.environ.get('PARTS_DIR') or os.path.join(ROOT, 'data', 'parts')
OUT = os.path.join(ROOT, "js", "data.js")

LINES = {"CH32V0", "CH32V1", "CH32V2", "CH32V3", "CH32V4", "CH32L1", "CH32X0", "CH32X3", "CH32H4",
         "CH32M", "CH64x", "CH56x", "CH57x", "CH58x", "CH59x"}
FEATURES = ["usbFS", "usbHS", "usbSS", "usbHost", "usbDevice", "usbPD", "ethernet", "ethPHY", "ble", "rf24",
            "can", "canFD", "adc", "dac", "opamp", "comparator", "touch", "lcd", "sdio", "extMem", "dvp", "i2s",
            "rtc", "crypto", "lowPower", "pioc"]
NUM = ["cores", "mhz", "flashKB", "flashTotalKB", "dataFlashKB", "ramKB", "pins", "gpio", "vMin", "vMax", "tempMin", "tempMax",
       "uart", "spi", "i2c", "i2s", "can", "adcBits", "adcChannels", "dacChannels", "opamps", "comparators",
       "touchChannels", "dmaChannels"]
TEXT = ["family", "status", "core", "isa", "fpu", "package", "packageSize", "usb", "eth", "radio", "timers", "debug"]
REQUIRED = ["id", "family", "line", "core", "package", "sources"]


def norm(p):
    """Normalise small inconsistencies so the UI can rely on types."""
    for k in NUM:
        p.setdefault(k, None)
        if isinstance(p[k], str):
            try:
                p[k] = float(p[k]) if "." in p[k] else int(p[k])
            except ValueError:
                p[k] = None
    for k in TEXT:
        p.setdefault(k, None)
    if isinstance(p.get("fpu"), str):
        f = p["fpu"].strip()
        p["fpu"] = "none" if f.lower() in ("none", "no", "aucune", "") else f
    feats = p.setdefault("features", {})
    for k in FEATURES:
        feats.setdefault(k, None)
    p.setdefault("notes", [])
    p.setdefault("supplyRanges", None)
    p.setdefault("usbSupplyRanges", None)
    return p


def validate(p, errors):
    pid = p.get("id", "?")
    for k in REQUIRED:
        if not p.get(k):
            errors.append(f"{pid}: missing {k}")
    if p.get("line") not in LINES:
        errors.append(f"{pid}: unknown line {p.get('line')!r}")
    for k in NUM:
        v = p.get(k)
        if v is not None and (not isinstance(v, (int, float)) or isinstance(v, bool)):
            errors.append(f"{pid}: {k} must be a number or null, got {v!r}")
    for k, v in p["features"].items():
        if k not in FEATURES:
            errors.append(f"{pid}: unknown feature {k}")
        if v not in (True, False, None):
            errors.append(f"{pid}: feature {k} must be true/false/null")
    for s in p.get("sources") or []:
        if not str(s.get("url", "")).startswith(("http://", "https://")):
            errors.append(f"{pid}: bad source url {s.get('url')!r}")
    if p.get("vMin") is not None and p.get("vMax") is not None and p["vMin"] > p["vMax"]:
        errors.append(f"{pid}: vMin > vMax")
    if p.get("gpio") is not None and p.get("pins") is not None and p["gpio"] > p["pins"]:
        errors.append(f"{pid}: gpio > pins")


def main():
    parts, errors, seen = [], [], {}
    files = sorted(glob.glob(os.path.join(PARTS, "*.json")))
    if not files:
        sys.exit("no data/parts/*.json files")
    for fn in files:
        with open(fn, encoding="utf-8") as fh:
            try:
                arr = json.load(fh)
            except json.JSONDecodeError as e:
                errors.append(f"{os.path.basename(fn)}: {e}")
                continue
        for p in arr:
            p = norm(p)
            validate(p, errors)
            if p["id"] in seen:
                errors.append(f"{p['id']}: duplicate (in {seen[p['id']]} and {os.path.basename(fn)})")
            seen[p["id"]] = os.path.basename(fn)
            parts.append(p)
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    checked = max((p.get("checkedAt") or "") for p in parts) or datetime.date.today().isoformat()
    data = {
        "meta": {
            "count": len(parts),
            "families": len({p["family"] for p in parts}),
            "checkedAt": checked,
            "built": datetime.date.today().isoformat(),
        },
        "parts": parts,
    }
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by tools/build_data.py from data/parts/*.json — edit those files, not this one. */\n")
        fh.write("window.WCH_DATA = ")
        json.dump(data, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";\n")
    print(f"OK: {len(parts)} parts, {data['meta']['families']} families -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
